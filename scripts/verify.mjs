import assert from 'node:assert/strict';

const base = process.argv[2];
if (!base || new URL(base).protocol !== 'https:') {
  throw new Error('Usage: node scripts/verify.mjs https://YOUR_IBM_APPLICATION_URL');
}
const home = await fetch(new URL('/', base), { signal: AbortSignal.timeout(120_000) });
assert.equal(home.status, 200, 'Home endpoint must return HTTP 200');
assert.match(home.headers.get('content-type'), /^text\/html/);
const html = await home.text();
assert.match(html, /Finding Love at a Hackathon/);
assert.match(html, /Make this word yours/);
assert.match(html, /Scene <strong>1<\/strong>/);
assert.match(html, /DEMO SCORES/);
const health = await fetch(new URL('/health', base), { signal: AbortSignal.timeout(30_000) });
assert.equal(health.status, 200, 'Health endpoint must return HTTP 200');
const status = await health.json();
assert.equal(status.status, 'ok');
assert.equal(status.app, 'ibm-hello-world');
assert.equal(status.framework, 'Next.js');
assert.equal(status.language, 'TypeScript');
assert.match(status.nextVersion, /^16\./);
const cssPath = html.match(/href="([^\"]+\.css(?:\?[^\"]*)?)"/)?.[1];
assert.ok(cssPath, 'Page must include a generated stylesheet');
const css = await fetch(new URL(cssPath.replaceAll('&amp;', '&'), base), { signal: AbortSignal.timeout(30_000) });
assert.equal(css.status, 200, 'Next.js stylesheet must be accessible');
assert.match(css.headers.get('content-type'), /^text\/css/);
console.log(`Verified Next.js ${status.nextVersion} / TypeScript, health JSON, and CSS over HTTPS at ${base}`);
const creatorPage = await fetch(new URL('/scene-creator', base), { signal: AbortSignal.timeout(30_000) });
assert.equal(creatorPage.status, 200, 'Scene Creator must be deployed');
const creatorHtml = await creatorPage.text();
assert.match(creatorHtml, /<title>Scene Creator<\/title>/);
assert.match(creatorHtml, /Your scene preview/);
assert.match(creatorHtml, /Back to learning/);
const legacyCreator = await fetch(new URL('/veo', base), { redirect: 'manual', signal: AbortSignal.timeout(30_000) });
assert.equal(legacyCreator.status, 307, 'The original Veo URL must remain a compatibility redirect');
assert.equal(new URL(legacyCreator.headers.get('location'), base).pathname, '/scene-creator');
const readiness = await fetch(new URL('/api/veo', base), { signal: AbortSignal.timeout(60_000) });
assert.equal(readiness.status, 200, 'Veo readiness route must be deployed');
const ready = await readiness.json();
assert.equal(typeof ready.ready, 'boolean');
assert.equal(typeof ready.requiresPassword, 'boolean');
console.log(`Scene Creator, /veo compatibility, and API reachable; Google OAuth readiness: ${ready.ready ? 'ready' : 'not configured/ready'}. No video generation submitted.`);
